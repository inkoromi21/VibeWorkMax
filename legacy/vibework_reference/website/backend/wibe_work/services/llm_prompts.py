def scrub_portrait_plan_jargon(text: str) -> str:
    """Убрать из портрета язык планов: сравнение вариантов, «ясность маршрута», ярлыки."""
    import re

    t = (text or "").strip()
    if not t:
        return t
    # Целые предложения / пункты с жаргоном планов
    sentence_pats = (
        r"[^.!?\n]*ясность\s+маршрута[^.!?\n]*[.!?]?",
        r"[^.!?\n]*когда\s+маршрут\s+станет\s+понятнее[^.!?\n]*[.!?]?",
        r"[^.!?\n]*имеет\s+смысл\s+сравнить[^.!?\n]*[.!?]?",
        r"[^.!?\n]*сравните\s+(?:ещё\s+)?с[^.!?\n]*[.!?]?",
        r"[^.!?\n]*сравнить\s+ещё\s+с[^.!?\n]*[.!?]?",
        r"[^.!?\n]*вариант(?:ы|ом|ами)?\s+[abcавс][^.!?\n]*[.!?]?",
        r"[^.!?\n]*план(?:ы|ом|ами)?\s+[abcавс][^.!?\n]*[.!?]?",
        r"[^.!?\n]*сценари[йя]\s+[abcавс][^.!?\n]*[.!?]?",
        r"[^.!?\n]*ближе\s+всего\s+выглядит[^.!?\n]*[.!?]?",
        r"[^.!?\n]*около\s+\d+\s*%\s+по\s+ответам[^.!?\n]*[.!?]?",
        r"[^.!?\n]*\(\s*около\s+\d+\s*%[^)]*\)[^.!?\n]*[.!]?",
    )
    for pat in sentence_pats:
        t = re.sub(pat, " ", t, flags=re.IGNORECASE)
    # Кавычки только с «плановыми» названиями (класс+ЕГЭ, колледж/СПО и т.п.)
    t = re.sub(
        r"[«\"][^»\"]{0,120}?(?:\+|/\s*СПО|колледж\s*/|11\s*класс\s*\+|профильн\w*\s+информатик|"
        r"универс\w*\s+через|прикладн\w*\s+информатик)[^»\"]{0,80}[»\"]",
        "",
        t,
        flags=re.IGNORECASE,
    )
    t = re.sub(r"\s*•\s*(?=\s*•|\s*$)", " ", t)
    t = re.sub(r"[ \t]{2,}", " ", t)
    t = re.sub(r"\n{3,}", "\n\n", t)
    t = re.sub(r"\n\s*\n", "\n", t)
    return t.strip(" \n•-–—")


def polish_analysis_narrative(text: str, *, max_chars: int = 1800) -> str:
    """Обрезка и лёгкая чистка ИИ-нарратива разбора перед показом в UI."""
    import re

    t = scrub_portrait_plan_jargon(text or "")
    if not t:
        return t
    t = re.sub(r"^#+\s*", "", t, flags=re.MULTILINE)
    t = re.sub(r"^\s*[-•*]\s+", "", t, flags=re.MULTILINE)
    # Убрать нумерацию «1) … 2)» в одном абзаце
    t = re.sub(r"(?m)^\s*\d+[\)\.]\s*", "", t)
    t = re.sub(r"\s+", " ", t).strip()
    if len(t) > max_chars:
        cut = t[: max_chars + 1]
        last = max(cut.rfind(". "), cut.rfind("! "), cut.rfind("? "))
        t = (cut[: last + 1] if last > max_chars // 2 else cut[:max_chars]).strip()
    return t


_MED_HALLUCINATION_RE = re.compile(
    r"медспец|медиц|сестрин|фармац|медколледж|здравоохран|клиник",
    re.IGNORECASE,
)
_IT_HALLUCINATION_RE = re.compile(
    r"\bIT\b|программист|backend|frontend|разработк",
    re.IGNORECASE,
)


def narrative_conflicts_with_profile(text: str, profile: dict | None) -> bool:
    """True, если ИИ-вывод ушёл в чужую сферу относительно анкеты."""
    if not text or not isinstance(profile, dict):
        return False
    from wibe_work.services.user_context import parse_interest_spheres

    spheres = set(parse_interest_spheres(profile))
    ms = str(profile.get("main_sphere") or "").strip()
    if ms:
        spheres.add(ms)
    low = text.lower()
    if _MED_HALLUCINATION_RE.search(low) and "medicine" not in spheres:
        return True
    # IT-жаргон при сферах без IT/data
    if _IT_HALLUCINATION_RE.search(text) and not (spheres & {"it_dev", "data"}):
        # «информатика» как школьный предмет — ок; «программист/backend» — нет
        if re.search(r"программист|backend|frontend|разработчик", low):
            return True
    return False


